"""Build the DuckDB database from the CSVs and run every query in sql/.

    python run_queries.py

1. Creates repair_shop.duckdb from schema.sql and data/*.csv (rebuilt from scratch each run).
2. Runs each sql/NN_name.sql file in order.
3. Writes each result to results/NN_name.md as a markdown table.

To explore the data yourself afterwards, open repair_shop.duckdb with the
DuckDB CLI or Python (duckdb.connect("repair_shop.duckdb")).
"""

from __future__ import annotations

import datetime as dt
import re
from decimal import Decimal
from pathlib import Path

import duckdb

from generate_data import TABLE_ORDER

ROOT = Path(__file__).resolve().parent
DATA_DIR = ROOT / "data"
SQL_DIR = ROOT / "sql"
RESULTS_DIR = ROOT / "results"
DB_PATH = ROOT / "repair_shop.duckdb"
MAX_ROWS = 40  # longer results are cut off in the markdown file; the query itself is unchanged


def build_database(db_path: Path | None = DB_PATH, data_dir: Path = DATA_DIR) -> duckdb.DuckDBPyConnection:
    """Create the tables from schema.sql and load every CSV. db_path=None builds it in memory."""
    if db_path is not None and db_path.exists():
        db_path.unlink()
    con = duckdb.connect(str(db_path) if db_path is not None else ":memory:")
    con.execute((ROOT / "schema.sql").read_text(encoding="utf-8"))
    for table in TABLE_ORDER:  # parent tables first, so each foreign key is checked as rows load
        csv_path = (data_dir / f"{table}.csv").as_posix()
        con.execute(f"COPY {table} FROM '{csv_path}' (FORMAT csv, HEADER true)")
    return con


def run_query(con: duckdb.DuckDBPyConnection, sql_path: Path) -> tuple[list[str], list[tuple]]:
    """Run one .sql file and return its column names and rows."""
    result = con.execute(sql_path.read_text(encoding="utf-8"))
    columns = [column[0] for column in result.description]
    return columns, result.fetchall()


def read_header(sql: str) -> tuple[str, list[str]]:
    """Split a query's leading comment block into its title and paragraphs."""
    lines = []
    for line in sql.splitlines():
        if not line.startswith("--"):
            break
        lines.append(line[2:].strip())
    title, paragraphs, current = lines[0], [], []
    for line in lines[1:] + [""]:
        if line:
            current.append(line)
        elif current:
            paragraphs.append(" ".join(current))
            current = []
    return title, paragraphs


def format_value(value, decimals: int = 0) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, float):
        return f"{value:.{decimals}f}"
    if isinstance(value, dt.datetime):
        return value.strftime("%Y-%m-%d %H:%M")
    if isinstance(value, dt.date):
        return value.isoformat()
    return str(value).replace("|", "\\|")


def is_numeric(values) -> bool:
    present = [v for v in values if v is not None]
    return bool(present) and all(isinstance(v, (int, float, Decimal)) for v in present)


def float_decimals(values) -> int:
    """Decimals a column of floats needs, so 4.5 and 4.58 print as 4.50 and 4.58."""
    floats = [v for v in values if isinstance(v, float)]
    return min(6, max((len(repr(v).partition(".")[2]) for v in floats), default=0))


def to_markdown(columns: list[str], rows: list[tuple], max_rows: int = MAX_ROWS) -> str:
    """A GitHub markdown table: numbers right-aligned with matching decimals, cut to max_rows rows."""
    by_column = list(zip(*rows)) if rows else [()] * len(columns)
    decimals = [float_decimals(values) for values in by_column]
    lines = [
        "| " + " | ".join(columns) + " |",
        "|" + "|".join("---:" if is_numeric(values) else "---" for values in by_column) + "|",
    ]
    for row in rows[:max_rows]:
        lines.append("| " + " | ".join(format_value(v, d) for v, d in zip(row, decimals)) + " |")
    if len(rows) > max_rows:
        lines += ["", f"_Showing the first {max_rows} of {len(rows)} rows._"]
    return "\n".join(lines)


def render_result(sql_path: Path, columns: list[str], rows: list[tuple]) -> str:
    title, paragraphs = read_header(sql_path.read_text(encoding="utf-8"))
    # "Question: ..." becomes "**Question:** ..."
    paragraphs = [re.sub(r"^(\w+):", r"**\1:**", p) for p in paragraphs]
    row_count = f"{len(rows)} row" + ("" if len(rows) == 1 else "s")
    parts = [
        f"# {title}",
        *paragraphs,
        f"Query: [`sql/{sql_path.name}`](../sql/{sql_path.name}) · {row_count}",
        to_markdown(columns, rows),
        "> Generated by `run_queries.py` from the synthetic dataset. "
        "The numbers show what the query does; they are not real business results.",
    ]
    return "\n\n".join(parts) + "\n"


def main() -> None:
    if not (DATA_DIR / "bookings.csv").exists():
        raise SystemExit("No data found in data/. Run `python generate_data.py` first.")

    con = build_database()
    RESULTS_DIR.mkdir(exist_ok=True)
    for old_result in RESULTS_DIR.glob("*.md"):  # so a renamed query can't leave a stale result behind
        old_result.unlink()

    for sql_path in sorted(SQL_DIR.glob("*.sql")):
        columns, rows = run_query(con, sql_path)
        with open(RESULTS_DIR / f"{sql_path.stem}.md", "w", encoding="utf-8", newline="\n") as f:
            f.write(render_result(sql_path, columns, rows))
        print(f"{sql_path.name:<36} {len(rows):>3} rows -> results/{sql_path.stem}.md")
    con.close()
    print(f"Database: {DB_PATH.name}")


if __name__ == "__main__":
    main()
